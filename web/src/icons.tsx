import type { SVGProps } from "react";

/**
 * The icon set.
 *
 * Glyphs come from the HackerNoon pixel-icon-library (MIT), drawn on a 24-unit
 * grid where every vertex lands on a whole unit. That grid is the whole point:
 * rendered with shape-rendering="crispEdges" the edges stay hard at any size,
 * which is what makes the set read as pixel art rather than as small vector
 * icons. Hand-drawing replacements would break that alignment, so anything
 * missing is composed from the library's own shapes instead — see PrevIcon and
 * NextIcon below.
 */

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  /** Edge length in px. Matches the design system's 16 / 18 / 20 / 24 steps. */
  size?: number;
}

function icon(children: React.ReactNode) {
  return function Glyph({ size = 20, ...props }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="currentColor"
        shapeRendering="crispEdges"
        aria-hidden="true"
        focusable="false"
        {...props}
      >
        {children}
      </svg>
    );
  };
}

